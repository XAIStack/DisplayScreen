FRAME_HEAD = (0x5A, 0xA5)
WRITE_CMD = 0x10
READ_CMD = 0x03


def crc16(data: bytes) -> int:
    hi = lo = 0xFF
    for byte in data:
        index = lo ^ byte
        lo = hi ^ _AUCHCRCHI[index]
        hi = _AUCHCRCLO[index]
    return (hi << 8) | lo


def _pack_write(addr: int, payload: bytes) -> bytes:
    if len(payload) % 2:
        payload += b"\x00"
    body = bytes([WRITE_CMD, (addr >> 8) & 0xFF, addr & 0xFF]) + payload
    length = len(body) + 2
    checksum = crc16(body)
    # On wire: CRC low byte first, then high byte (e.g. 0xC465 -> 65 C4).
    return bytes([*FRAME_HEAD, length, *body, checksum & 0xFF, (checksum >> 8) & 0xFF])


def build_write_word(addr: int, value: int) -> bytes:
    """Write one 16-bit word (progress bar / numeric control)."""
    value &= 0xFFFF
    payload = bytes([(value >> 8) & 0xFF, value & 0xFF])
    return _pack_write(addr, payload)


def build_write_words(addr: int, values: list[int]) -> bytes:
    """Write consecutive 16-bit words (e.g. screen RTC registers 0x7002)."""
    payload = bytearray()
    for value in values:
        value &= 0xFFFF
        payload.extend([(value >> 8) & 0xFF, value & 0xFF])
    return _pack_write(addr, bytes(payload))


def build_write_dword(addr: int, value: int) -> bytes:
    """Write a 32-bit value as two VP words, high word first (e.g. YYMMDD / HHMMSS)."""
    value &= 0xFFFFFFFF
    return build_write_words(addr, [(value >> 16) & 0xFFFF, value & 0xFFFF])


def _encode_levetop_string(text: str, encoding: str = "gb2312") -> bytes:
    """
    LEVETOP string controls expect 16-bit character units (GB2312/GBK).
    ASCII must be sent as 0x00 + byte, not single-byte sequences.
    """
    payload = bytearray()
    for ch in text:
        raw = ch.encode(encoding, errors="replace")
        if len(raw) == 1:
            payload.extend((0x00, raw[0]))
        elif len(raw) == 2:
            payload.extend(raw)
        else:
            payload.extend((0x00, ord("?")))
    payload.extend((0x00, 0x00))
    return bytes(payload)


def build_write_string(addr: int, text: str, *, encoding: str = "gb2312") -> bytes:
    """Write null-terminated string (string / text controls)."""
    raw = _encode_levetop_string(text, encoding)
    return _pack_write(addr, raw)


def build_write_packed_ascii(addr: int, text: str) -> bytes:
    """
    Write 8-bit ASCII into VP words (two chars per 16-bit word).
    Used by LEVETOP 字符型 controls, not 16-bit GB2312 字符串.
    """
    payload = text.encode("ascii", errors="replace") + b"\x00"
    return _pack_write(addr, payload)


def format_hex(packet: bytes) -> str:
    return " ".join(f"{b:02X}" for b in packet)


def build_read_words(addr: int, word_count: int) -> bytes:
    """Read word_count 16-bit words starting at addr (cmd 0x03)."""
    word_count &= 0xFFFF
    body = bytes(
        [
            READ_CMD,
            (addr >> 8) & 0xFF,
            addr & 0xFF,
            (word_count >> 8) & 0xFF,
            word_count & 0xFF,
        ]
    )
    length = len(body) + 2
    checksum = crc16(body)
    return bytes([*FRAME_HEAD, length, *body, checksum & 0xFF, (checksum >> 8) & 0xFF])


def parse_read_words(response: bytes) -> list[int]:
    """Parse read response payload words (cmd 0x03); skips write-ack prefix frames."""
    offset = 0
    while offset + 9 <= len(response):
        if response[offset] != 0x5A or response[offset + 1] != 0xA5:
            offset += 1
            continue
        length = response[offset + 2]
        frame_end = offset + 3 + length
        if frame_end > len(response):
            break
        if response[offset + 3] == READ_CMD:
            word_count = (response[offset + 7] << 8) | response[offset + 8]
            values: list[int] = []
            pos = offset + 9
            for _ in range(word_count):
                if pos + 1 >= frame_end - 2:
                    break
                values.append((response[pos] << 8) | response[pos + 1])
                pos += 2
            if values:
                return values
        offset = frame_end
    return []


def describe_feedback(data: bytes) -> str:
    """Parse write-ack frame: 5A A5 04 10 FF/00 CRC."""
    if len(data) < 7 or data[0] != 0x5A or data[1] != 0xA5:
        return format_hex(data) if data else "(no response)"
    if data[3] == WRITE_CMD and data[4] == 0xFF:
        return "ACK OK (CRC passed)"
    if data[3] == WRITE_CMD and data[4] == 0x00:
        return "ACK FAIL (CRC error)"
    return format_hex(data)
